/* USER CODE BEGIN 4 */
void Motor_SetPulse(uint8_t ch, uint16_t val)
{
    if (val < 1000) val = 1000;
    if (val > 2000) val = 2000;

    switch(ch) {
        case 0: __HAL_TIM_SET_COMPARE(&htim2, TIM_CHANNEL_1, val); break; // PA15
        case 1: __HAL_TIM_SET_COMPARE(&htim2, TIM_CHANNEL_2, val); break; // PB3
        case 2: __HAL_TIM_SET_COMPARE(&htim2, TIM_CHANNEL_3, val); break; // PB10
        case 3: __HAL_TIM_SET_COMPARE(&htim2, TIM_CHANNEL_4, val); break; // PB11
    }
}

uint16_t ADC_Map(uint32_t adc_val, uint16_t out_min, uint16_t out_max)
{
    return (uint16_t)(out_min + ((uint32_t)(adc_val) * (out_max - out_min)) / 4095);
}

void Control_Loop(void)
{
    uint16_t throttle = ADC_Map(ADC_THROTTLE, 1000, 2000);
    int16_t roll      = (int16_t)ADC_Map(ADC_ROLL,  0, 400) - 200;
    int16_t pitch     = (int16_t)ADC_Map(ADC_PITCH, 0, 400) - 200;

    // X-frame quadcopter
    motor[0] = throttle + roll - pitch;  // Motor 1 PA15
    motor[1] = throttle - roll - pitch;  // Motor 2 PB3
    motor[2] = throttle + roll + pitch;  // Motor 3 PB10
    motor[3] = throttle - roll + pitch;  // Motor 4 PB11

    for (uint8_t i = 0; i < 4; i++) {
        Motor_SetPulse(i, motor[i]);
    }

    // Nhấp nháy LED PC13 (active low)
    HAL_GPIO_TogglePin(GPIOC, GPIO_PIN_13);
}

